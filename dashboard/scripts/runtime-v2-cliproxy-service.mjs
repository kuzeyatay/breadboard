#!/usr/bin/env node

import { spawn } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

function fail(message) {
  process.stderr.write(`[cliproxy] ${message}\n`);
  process.exit(1);
}

function pathWithin(root, candidate) {
  const relative = path.relative(path.resolve(root), path.resolve(candidate));
  return relative === "" || (
    relative !== ".." &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  );
}

function yamlString(value) {
  return JSON.stringify(value.replaceAll("\\", "/"));
}

function readOrCreateSecret(home, fileName, environmentName) {
  const supplied = process.env[environmentName]?.trim();
  if (supplied) return supplied;
  const secretPath = path.join(home, fileName);
  const metadata = fs.lstatSync(secretPath, { throwIfNoEntry: false });
  if (metadata) {
    if (!metadata.isFile() || metadata.isSymbolicLink() || metadata.size > 4096) {
      fail(`${fileName} is not a trusted direct secret file.`);
    }
    const existing = fs.readFileSync(secretPath, "utf8").trim();
    if (existing) return existing;
  }
  const secret = crypto.randomBytes(32).toString("hex");
  fs.writeFileSync(secretPath, `${secret}\n`, { encoding: "utf8", mode: 0o600, flag: "wx" });
  return secret;
}

const args = process.argv.slice(2);
if (args.length !== 2 || args[0] !== "--port" || !/^\d{1,5}$/u.test(args[1])) {
  fail("Expected only --port <runtime-minted-port>.");
}
const port = Number.parseInt(args[1], 10);
if (port < 1 || port > 65_535) fail("The runtime-minted port is invalid.");

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDirectory, "..", "..");
const runtimeRoot = path.resolve(appRoot, "..");
const binary = path.join(runtimeRoot, "bin", process.platform === "win32" ? "cli-proxy-api.exe" : "cli-proxy-api");
const binaryMetadata = fs.lstatSync(binary, { throwIfNoEntry: false });
if (!binaryMetadata?.isFile() || binaryMetadata.isSymbolicLink()) {
  fail("The reviewed packaged CLIProxyAPI executable is unavailable.");
}

const dataRootValue = process.env.BREADBOARD_DATA_DIR?.trim();
if (!dataRootValue || !path.isAbsolute(dataRootValue)) fail("BREADBOARD_DATA_DIR is unavailable.");
const dataRoot = path.resolve(dataRootValue);
const home = path.join(dataRoot, "cliproxy");
if (!pathWithin(dataRoot, home)) fail("The CLIProxyAPI home escaped Runtime data.");
fs.mkdirSync(home, { recursive: true });
fs.mkdirSync(path.join(home, "auth"), { recursive: true });

const apiKey = readOrCreateSecret(home, "api-key", "CLIPROXY_API_KEY");
const managementKey = readOrCreateSecret(home, "management-key", "CLIPROXY_MANAGEMENT_KEY");
const configPath = path.join(home, "config.yaml");
fs.writeFileSync(
  configPath,
  `# Generated by Breadboard's sealed Runtime V2 launcher.\n` +
    `host: "127.0.0.1"\n` +
    `port: ${port}\n` +
    `auth-dir: ${yamlString(path.join(home, "auth"))}\n` +
    `api-keys:\n  - ${yamlString(apiKey)}\n` +
    `debug: false\nusage-statistics-enabled: false\nlogging-to-file: false\n` +
    `request-retry: 3\nmax-retry-interval: 30\n` +
    `remote-management:\n  allow-remote: false\n  secret-key: ${yamlString(managementKey)}\n  disable-control-panel: true\n` +
    `quota-exceeded:\n  switch-project: true\n  switch-preview-model: false\n` +
    `routing:\n  strategy: "round-robin"\n`,
  { encoding: "utf8", mode: 0o600 },
);

const child = spawn(binary, ["--config", configPath], {
  cwd: home,
  detached: false,
  windowsHide: true,
  stdio: "inherit",
  env: { ...process.env, WRITABLE_PATH: home },
});
child.once("error", (error) => fail(`CLIProxyAPI failed to start: ${error.message}`));
child.once("exit", (code, signal) => {
  if (signal) process.stderr.write(`[cliproxy] stopped by ${signal}\n`);
  process.exit(code ?? 1);
});
const stop = () => {
  if (!child.killed) child.kill("SIGTERM");
};
process.once("SIGINT", stop);
process.once("SIGTERM", stop);
