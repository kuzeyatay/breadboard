import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import { installQuartzDocumentEditor } from "../../quartz/quartz/components/scripts/documentEditorLoader.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// The packaged static service ships scripts independently of the Quartz template.
fs.writeFileSync(path.join(root, 'scripts/quartz-document-editor-loader.mjs'), `// Generated by build-quartz-editor.mjs.\nexport ${installQuartzDocumentEditor.toString()}\n`);
await build({ entryPoints: [path.join(root, "src/lib/quartz-editor/index.ts")],
  outfile: path.join(root, "public/quartz-editor/editor.js"), bundle: true, minify: true,
  platform: "browser", format: "iife", globalName: "BreadboardDocumentEditor", target: "es2022",
  define: { "process.env.NODE_ENV": '"production"' }, loader: { ".woff2": "file", ".woff": "file", ".ttf": "file" },
});
console.log("[quartz] Document editor built.");
