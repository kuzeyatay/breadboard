// Preparing the OpenMAIC runtime: a Breadboard-owned copy of the clone,
// installed and built.
//
// Setup runs only because a person pressed the button in the settings dialog,
// and it never touches the checkout. A staging copy of the source is made under
// the toolchains root, dependencies go in with pnpm through corepack, the app is
// built, and only then is the copy swapped into place — so a failed setup leaves
// the previous runtime exactly as it was.
//
// One change is made to the copy, and only on Windows. The `@openmaic/importer`
// package is bundled with `rollup-plugin-node-globals`, which inlines each
// module's `__dirname` as a path relative to `/`. On this machine that path
// begins `\Users\20252082\...`, and `\2` is an octal escape the parser refuses,
// so the build dies before it starts. Passing the package directory as the
// plugin's `baseDir` keeps the inlined paths relative and digit-free. It is
// applied to the copy, documented here and in docs/OPENMAIC_INTEGRATION.md, and
// worth sending upstream.

