export interface ClassroomSetupProgress {
  running: boolean;
  step: string;
  /** The last lines the install or build wrote, for a dialog to show. */
  log: string;
  error: string;
  startedAt: string | null;
  finishedAt: string | null;
}

export interface ClassroomSetupStatus {
  ready: boolean;
  reason: string;
  clone: { found: boolean; path: string };
  runtime: { path: string; installed: boolean; built: boolean };
  service: { running: boolean; baseUrl: string; model: string };
  setup: ClassroomSetupProgress;
}

interface SetupState extends ClassroomSetupProgress {
  child: ChildProcess | null;
  promise: Promise<void> | null;
}

const runtimeGlobal = globalThis as typeof globalThis & {
  __breadboardClassroomSetup?: SetupState;
};

const state: SetupState = runtimeGlobal.__breadboardClassroomSetup ?? {
  running: false,
  step: "",
  log: "",
  error: "",
  startedAt: null,
  finishedAt: null,
  child: null,
  promise: null,
};
runtimeGlobal.__breadboardClassroomSetup = state;

/** Directories that are build output, state, or not part of the app at all. */
const EXCLUDED_DIRECTORIES = new Set([
  ".git",
  ".github",
  ".next",
  ".worktrees",
  "node_modules",
  "data",
  "logs",
  "out",
  "coverage",
  "test-results",
  "playwright-report",
  "e2e",
  "eval",
]);

const INSTALL_TIMEOUT_MS = 90 * 60_000;
const BUILD_TIMEOUT_MS = 30 * 60_000;

export function setupStatus(env: NodeJS.ProcessEnv = process.env): ClassroomSetupStatus {
  const availability = classroomAvailability(env);
  const service = currentService();
  return {
    ready: availability.available,
    reason: availability.reason ?? "",
    clone: { found: availability.cloned, path: availability.sourceRoot ?? "" },
    runtime: {
      path: availability.runtimeRoot,
      installed: availability.installed,
      built: availability.built,
    },
    service: {
      running: Boolean(service),
      baseUrl: service?.baseUrl ?? "",
      model: service?.model ?? "",
    },
    setup: {
      running: state.running,
      step: state.step,
      log: state.log,
      error: state.error,
      startedAt: state.startedAt,
      finishedAt: state.finishedAt,
    },
  };
}

async function copySource(source: string, staging: string): Promise<void> {
  fs.mkdirSync(path.dirname(staging), { recursive: true });
  await fs.promises.cp(source, staging, {
    recursive: true,
    dereference: false,
    errorOnExist: false,
    filter: (from) => {
      const relative = path.relative(source, from);
      if (!relative) return true;
      const segments = relative.split(path.sep);
      if (segments.some((segment) => EXCLUDED_DIRECTORIES.has(segment))) return false;
      // The vendored parser bundle is regenerated by the install; a stale copy
      // would satisfy the build's assertion with the wrong bytes.
      if (relative.startsWith(path.join("public", "vendor", "maic-importer"))) return false;
      // Workspace package builds are regenerated too.
      if (/^packages[\\/].+[\\/]dist(?:[\\/]|$)/.test(relative)) return false;
      return true;
    },
  });
}

/** The Windows-only build fix described at the top of this file. */
export function applyImporterBuildFix(root: string, platform: NodeJS.Platform = process.platform): boolean {
  if (platform !== "win32") return false;
  const config = path.join(root, "packages", "@openmaic", "importer", "rollup.config.js");
  let source: string;
  try {
    source = fs.readFileSync(config, "utf8");
  } catch {
    return false;
  }
  if (source.includes("baseDir: process.cwd()")) return true;
  const patched = source.replace(/\bglobals\(\)/, "globals({ baseDir: process.cwd() })");
  if (patched === source) return false;
  fs.writeFileSync(config, patched, "utf8");
  return true;
}

/**
 * A `pnpm` on PATH for the install. OpenMAIC's postinstall runs `pnpm run build`
 * in every workspace package by bare name, and corepack is how pnpm is meant to
 * be reached here, so the shim just forwards to corepack through this Node.
 */
/** Use Node for the fixed dist cleanup in the owned Windows runtime copy. */
export function applyPortablePackageBuildScripts(root: string, platform: NodeJS.Platform = process.platform): number {
  if (platform !== "win32") return 0;
  let changed = 0;
  for (const name of ["dsl", "generation", "storage", "importer", "renderer", "editor"]) {
    const directory = path.join(root, "packages", "@openmaic", name);
    const file = path.join(directory, "package.json");
    if (!fs.existsSync(file)) continue;
    const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
    let patched = false;
    for (const key of ["build", "clean"]) {
      const script = manifest.scripts?.[key];
      if (typeof script !== "string") continue;
      const parts = script.split("&&").map((part: string) => part.trim());
      if (!parts.includes("rm -rf dist")) continue;
      manifest.scripts[key] = parts.map((part: string) => part === "rm -rf dist" ? "node .breadboard-clean-dist.cjs" : part).join(" && ");
      patched = true;
    }
    if (!patched) continue;
    // The helper is inside this package; its absolute target can only be dist.
    fs.writeFileSync(path.join(directory, ".breadboard-clean-dist.cjs"),
      "const fs=require('node:fs'),path=require('node:path');\n" +
      "const target=path.resolve(__dirname,'dist');\n" +
      "if(path.dirname(target)!==path.resolve(__dirname))throw Error('Invalid build output');\n" +
      "const entry=fs.lstatSync(target,{throwIfNoEntry:false});\n" +
      "if(entry)fs.rmSync(target,{recursive:!entry.isSymbolicLink(),force:true});\n", "utf8");
    fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n", "utf8");
    changed++;
  }
  return changed;
}

/** A one-shot Windows bundle must not stay alive for leaked TypeScript watchers.
 * Keep the real Rollup CLI, outputs and exit code; only its file watchers become
 * non-persistent. The upstream development/watch commands are left alone. */
export function applyNonWatchingRollupBuildScripts(root: string, platform: NodeJS.Platform = process.platform): number {
  if (platform !== "win32") return 0;
  let changed = 0;
  for (const name of ["renderer", "editor"]) {
    const directory = path.join(root, "packages", "@openmaic", name);
    const file = path.join(directory, "package.json");
    if (!fs.existsSync(file)) continue;
    const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
    if (typeof manifest.scripts?.build !== "string") continue;
    const parts = manifest.scripts.build.split("&&").map((part: string) => part.trim());
    if (!parts.includes("rollup -c")) continue;
    const helper = ".breadboard-rollup-build.cjs";
    fs.writeFileSync(path.join(directory, helper),
      "const fs=require('node:fs'),path=require('node:path');\n" +
      "if(process.argv.length!==3||process.argv[2]!=='-c')throw Error('Expected a one-shot Rollup build');\n" +
      "for(const name of ['watch','watchFile']){const original=fs[name];fs[name]=function(...args){const watcher=original.apply(this,args);watcher?.unref?.();return watcher;};}\n" +
      "require('node:module').syncBuiltinESMExports();\n" +
      "const cli=path.join(path.dirname(require.resolve('rollup/package.json')),'dist','bin','rollup');\n" +
      "process.argv=[process.execPath,cli,'-c'];\n" +
      "require(cli);\n", "utf8");
    manifest.scripts.build = parts.map((part: string) => part === "rollup -c" ? `node ${helper} -c` : part).join(" && ");
    fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n", "utf8");
    changed++;
  }
  return changed;
}

export function writePnpmShims(toolsDir: string, corepack: string, execPath: string = process.execPath, throughCorepack = true): void {
  const executable = runtimeProcessPath(execPath);
  const entry = runtimeProcessPath(corepack);
  fs.mkdirSync(toolsDir, { recursive: true });
  fs.writeFileSync(
    path.join(toolsDir, "pnpm.cmd"),
    `@echo off\r\n"${executable}" "${entry}" ${throughCorepack ? "pnpm " : ""}%*\r\n`,
    "utf8",
  );
  fs.writeFileSync(
    path.join(toolsDir, "pnpm"),
    `#!/bin/sh\nexec "${executable}" "${entry}" ${throughCorepack ? "pnpm " : ""}"$@"\n`,
    { encoding: "utf8", mode: 0o755 },
  );
}

/**
 * The install and build environment. `ALLOWED_FRAME_ANCESTORS` is here and not
 * only at start because OpenMAIC's `next.config.ts` reads it while building —
 * the CSP header lands in the routes manifest — so a build without it serves
 * `frame-ancestors 'self'` whatever the server is later started with, and the
 * run card's frame stays blank. Found by framing one.
 */
export function installEnvironment(toolsDir: string, source: NodeJS.ProcessEnv = process.env): NodeJS.ProcessEnv {
  const env = { ...source };
  // This is another Next app. The dashboard's serialized standalone config
  // bypasses its config loader and has no generateBuildId function; inherited
  // worker and dotenv sentinels likewise belong only to the parent process.
  for (const key of Object.keys(env)) {
    if (key.startsWith("__NEXT_PRIVATE_") || key === "__NEXT_PROCESSED_ENV") delete env[key];
  }
  const pathKey = Object.keys(env).find((key) => key.toUpperCase() === "PATH") ?? "PATH";
  return {
    ...env,
    [pathKey]: `${toolsDir}${path.delimiter}${env[pathKey] ?? ""}`,
    COREPACK_ENABLE_DOWNLOAD_PROMPT: "0",
    COREPACK_ENABLE_STRICT: "0",
    NEXT_TELEMETRY_DISABLED: "1",
    NO_COLOR: "1",
    CI: "1",
    ALLOWED_FRAME_ANCESTORS: FRAME_ANCESTORS,
  };
}

export function runClassroomStep(
  label: string,
  command: string,
  args: string[],
  options: { cwd: string; env: NodeJS.ProcessEnv; timeoutMs: number },
): Promise<void> {
  state.step = label;
  state.log = "";
  return new Promise((resolve, reject) => {
    const child = spawn(runtimeProcessPath(command), args.map(arg => runtimeProcessPath(arg)), {
      cwd: runtimeProcessPath(options.cwd),
      env: classroomProcessEnvironment(options.env),
      windowsHide: true,
      stdio: ["ignore", "pipe", "pipe"],
    });
    state.child = child;
    const collect = (chunk: string) => {
      state.log = `${state.log}${chunk}`.slice(-6_000);
    };
    child.stdout?.setEncoding("utf8");
    child.stderr?.setEncoding("utf8");
    child.stdout?.on("data", collect);
    child.stderr?.on("data", collect);
    let timedOut = false;
    let stopWatch: ReturnType<typeof setTimeout> | undefined;
    const timer = setTimeout(() => {
      timedOut = true;
      try {
        child.kill();
      } catch {
        // Already gone.
      }
      // Wait for process/pipe closure before any rollback touches its cwd.
      stopWatch = setTimeout(() => reject(Object.assign(
        new Error(`${label} exceeded its time limit; process exit is unconfirmed. The installation was preserved.`),
        { preserveInstallation: true },
      )), 30_000);
      stopWatch.unref?.();
    }, options.timeoutMs);
    timer.unref?.();
    child.on("error", (error) => {
      clearTimeout(timer);
      reject(new Error(`${label} could not start: ${error.message}`));
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      clearTimeout(stopWatch);
      state.child = null;
      if (timedOut) reject(new Error(`${label} ran past its time limit and was stopped.`));
      else if (code === 0) resolve();
      else reject(new Error(`${label} failed (exit ${code ?? "unknown"}).`));
    });
  });
}

/** Modern bundled Node may omit Corepack. Install only the package-manager
 * version and tarball integrity pinned by the trusted OpenMAIC source. */
export async function prepareClassroomPackageManager(
  source: string, toolsDir: string, env: NodeJS.ProcessEnv,
  run: typeof runClassroomStep = runClassroomStep,
  corepack: string | null = corepackEntry(),
): Promise<{ entry: string; prefix: string[] }> {
  if (corepack) return {entry: corepack, prefix: ["pnpm"]};
  const manifest = JSON.parse(fs.readFileSync(path.join(source, "package.json"), "utf8"));
  const pin = /^pnpm@(\d+\.\d+\.\d+)\+sha512\.([a-f0-9]{128})$/u.exec(manifest.packageManager ?? "");
  if (!pin) throw new Error("OpenMAIC must pin its pnpm version and SHA-512 integrity before setup.");
  const entry = path.join(toolsDir, "node_modules", "pnpm", "bin", "pnpm.cjs");
  const valid = () => {
    try {
      const metadata = fs.lstatSync(entry);
      if (!metadata.isFile() || metadata.isSymbolicLink() || !sameRuntimePath(fs.realpathSync.native(entry), entry)) return false;
      const installed = JSON.parse(fs.readFileSync(path.join(toolsDir, "node_modules", "pnpm", "package.json"), "utf8"));
      const lock = JSON.parse(fs.readFileSync(path.join(toolsDir, "package-lock.json"), "utf8"));
      const expected = `sha512-${Buffer.from(pin[2], "hex").toString("base64")}`;
      return installed.version === pin[1] && lock.packages?.["node_modules/pnpm"]?.integrity === expected;
    } catch { return false; }
  };
  if (!valid()) {
    const npm = path.join(path.dirname(process.execPath), "node_modules", "npm", "bin", "npm-cli.js");
    if (!fs.statSync(npm, {throwIfNoEntry: false})?.isFile()) throw new Error("The bundled Node package manager is missing. Repair Breadboard's Node runtime before setting up Classroom.");
    fs.mkdirSync(toolsDir, {recursive: true});
    await run("Preparing the package manager", process.execPath,
      [npm, "install", "--prefix", toolsDir, "--save-exact", "--ignore-scripts", "--no-audit", "--no-fund", `pnpm@${pin[1]}`],
      {cwd: toolsDir, env, timeoutMs: INSTALL_TIMEOUT_MS});
    if (!valid()) throw new Error("The installed pnpm package does not match OpenMAIC's pinned integrity.");
  }
  return {entry, prefix: []};
}

/**
 * Point the runtime copy's `data` at the stable data directory. A junction on
 * Windows (no privilege needed), a symlink elsewhere; idempotent, and a real
 * directory already there — a classroom written before this existed — is
 * moved into the stable one rather than shadowed.
 */
export function ensureClassroomDataLink(
  link: string = classroomDataLink(),
  target: string = classroomDataDir(),
): void {
  fs.mkdirSync(target, { recursive: true });
  const existing = fs.lstatSync(link, { throwIfNoEntry: false });
  if (existing?.isSymbolicLink()) {
    try {
      if (path.resolve(fs.readlinkSync(link)) === path.resolve(target)) return;
    } catch {
      // Unreadable link: replaced below.
    }
    fs.rmSync(link, { recursive: false, force: true });
  } else if (existing?.isDirectory()) {
    for (const entry of fs.readdirSync(link)) {
      const from = path.join(link, entry);
      const to = path.join(target, entry);
      if (!fs.existsSync(to)) fs.renameSync(from, to);
    }
    fs.rmSync(link, { recursive: true, force: true });
  } else if (existing) {
    fs.rmSync(link, { force: true });
  }
  fs.mkdirSync(path.dirname(link), { recursive: true });
  fs.symlinkSync(target, link, process.platform === "win32" ? "junction" : "dir");
}

/**
 * The install and build happen at the runtime's final path, not in staging.
 * pnpm lays out `node_modules` with junctions whose targets are absolute, so a
 * tree installed under one directory and renamed to another points at a place
 * that no longer exists. The previous runtime is kept beside it until the new
 * one has built, and put back if it does not.
 */
async function perform(): Promise<void> {
  const source = resolveClassroomSourceRoot();
  if (!source) {
    throw new Error(
      "The OpenMAIC clone was not found. Clone THU-MAIC/OpenMAIC beside the dashboard first.",
    );
  }
  const destination = classroomInstallationRoot();
  const staging = classroomStagingRoot(randomUUID().slice(0, 8));
  const previous = `${destination}.previous-${randomUUID().slice(0, 8)}`;
  const toolsDir = classroomToolsDir();
  const cache = managedPayloadTarget(dashboardDataDir(), "runtime-v2/toolchains/cache");
  const env = { ...installEnvironment(toolsDir), COREPACK_HOME: path.join(cache, "corepack"), npm_config_cache: path.join(cache, "npm") };
  const manager = await prepareClassroomPackageManager(source, toolsDir, env);

  state.step = "Copying the source";
  await copySource(source, staging);
  applyImporterBuildFix(staging);
  applyPortablePackageBuildScripts(staging);
  applyNonWatchingRollupBuildScripts(staging);
  writePnpmShims(toolsDir, manager.entry, process.execPath, manager.prefix.length > 0);

  // The running server holds files open on Windows; it restarts on the next run.
  stopService();
  if (fs.existsSync(destination)) fs.renameSync(destination, previous);
  try {
    fs.renameSync(staging, destination);
  } catch (error) {
    await fs.promises.rm(staging, { recursive: true, force: true });
    if (fs.existsSync(previous)) fs.renameSync(previous, destination);
    throw error;
  }

  try {
    await runClassroomStep(
      "Installing dependencies",
      process.execPath,
      [manager.entry, ...manager.prefix, "install", "--frozen-lockfile", "--store-dir", path.join(cache, "pnpm")],
      { cwd: destination, env, timeoutMs: INSTALL_TIMEOUT_MS },
    );
    await runClassroomStep(
      "Building the app",
      process.execPath,
      [manager.entry, ...manager.prefix, "run", "build"],
      { cwd: destination, env, timeoutMs: BUILD_TIMEOUT_MS },
    );
    if (!fs.existsSync(path.join(destination, ".next", "BUILD_ID"))) {
      throw new Error("The build finished without producing a servable app.");
    }
    ensureClassroomDataLink(path.join(destination, "data"));
  } catch (error) {
    state.step = "Restoring the previous runtime";
    state.error = error instanceof Error ? error.message : "Setup failed.";
    if (error && typeof error === "object" && "preserveInstallation" in error) throw error;
    try {
      await fs.promises.rm(destination, { recursive: true, force: true });
      if (fs.existsSync(previous)) fs.renameSync(previous, destination);
    } catch (rollback) {
      throw new Error(
        `${error instanceof Error ? error.message : "Setup failed."} The previous installation was preserved at ${previous}; cleanup could not finish: ${rollback instanceof Error ? rollback.message : String(rollback)}`,
      );
    }
    throw error;
  }
  // A previous runtime from before the data junction existed may still hold
  // classrooms in a real `data/`; carry them over before it goes.
  const previousData = path.join(previous, "data");
  if (fs.lstatSync(previousData, { throwIfNoEntry: false })?.isDirectory()) {
    ensureClassroomDataLink(previousData);
  }
  await fs.promises.rm(previous, { recursive: true, force: true });
  if (sameRuntimePath(destination, managedPayloadTarget(dashboardDataDir(), "runtime-v2/toolchains/openmaic"))) {
    markManagedPayloadReady(dashboardDataDir(), "runtime-v2/toolchains/openmaic");
  }
}

/**
 * Start setup in the background and return at once; `setupStatus()` reports
 * progress. A second press while one runs joins it rather than starting another.
 */
export function startClassroomSetup(): ClassroomSetupProgress {
  if (!state.running) {
    state.running = true;
    state.step = "Starting";
    state.log = "";
    state.error = "";
    state.startedAt = new Date().toISOString();
    state.finishedAt = null;
    state.promise = perform()
      .then(() => {
        state.step = "Ready";
      })
      .catch((error: unknown) => {
        state.error = error instanceof Error ? error.message : "Setup failed.";
        state.step = "Failed";
      })
      .finally(() => {
        state.running = false;
        state.child = null;
        state.finishedAt = new Date().toISOString();
        state.promise = null;
      });
  }
  return setupStatus().setup;
}

/** The in-flight setup, for a caller that wants to wait on it. */
export function classroomSetupPromise(): Promise<void> | null {
  return state.promise;
}
