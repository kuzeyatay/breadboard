// The Postiz Docker Compose stack.
//
// Breadboard runs Postiz's *upstream* compose file untouched and layers a
// generated override on top. Nothing in the vendored clone is edited, so
// pulling upstream stays a plain `git pull`, while the override carries the
// things that must not ship as upstream defaults: a real JWT secret, the port
// Breadboard published, and whatever social OAuth apps the user configured.
//
// The override also sets NOT_SECURED, which makes Postiz return its auth JWT in
// a response header instead of a Secure cookie. That is what lets ./bootstrap.ts
// register the first account over plain http on localhost.

import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import type { SocialsManagerConfig, PostizCredentials } from "./config.ts";
import { composeCommand, ensureDockerRunning, run, type DockerStatus } from "./docker.ts";

export type StackState =
  | "running"
  | "starting"
  | "stopped"
  | "docker_unavailable"
  | "not_installed";

export interface StackStatus {
  state: StackState;
  docker: DockerStatus;
  /** True once the Postiz HTTP endpoint answers. */
  reachable: boolean;
  reason?: string;
}

