import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { build } from "esbuild";

// Exercise the real SDK and SSE parser without opening the application database.
const bundle = await build({
  entryPoints: [fileURLToPath(new URL("../src/lib/hermes/artifact-image-service.ts", import.meta.url))],
  bundle: true, platform: "node", format: "cjs", packages: "external", write: false,
  plugins: [{ name: "no-artifact-persistence", setup(builder) {
    builder.onResolve({ filter: /^\.\/artifact-store\.ts$/ }, () => ({ path: "store", namespace: "fixture" }));
    builder.onLoad({ filter: /.*/, namespace: "fixture" }, () => ({
      contents: 'export function createImportedArtifact() { throw new Error("Unexpected persistence during generation"); }',
    }));
  } }],
});
const bundledModule = { exports: {} };
new Function("require", "module", "exports", bundle.outputFiles[0].text)(createRequire(import.meta.url), bundledModule, bundledModule.exports);
const { generateArtifactImage } = bundledModule.exports;
const failure = (message) => ({ type: "response.failed", response: { error: { message } } });
const image = (bytes) => ({ type: "response.output_item.done", item: {
  type: "image_generation_call", id: "ig_test", result: bytes.toString("base64"),
} });
const completed = { type: "response.completed", response: { output: [], usage: { total_tokens: 23 } } };

async function withProvider(turns, work) {
  const originalFetch = globalThis.fetch;
  const requests = [];
  globalThis.fetch = async (url, init) => {
    assert.equal(String(url), "http://image-provider.test/v1/responses");
    const events = turns[requests.length];
    requests.push({ body: JSON.parse(init.body), signal: init.signal });
    assert.ok(events, "must not send an unexpected extra generation request");
    return new Response(events.map(event => `event: ${event.type}\ndata: ${JSON.stringify(event)}\n\n`).join("") + "data: [DONE]\n\n", {
      headers: { "content-type": "text/event-stream" },
    });
  };
  try { await work(requests); } finally { globalThis.fetch = originalFetch; }
}

const input = { baseURL: "http://image-provider.test/v1", prompt: "A seaside villa" };

test("a large streamed image with Unicode metadata and base64 padding decodes without a retry", async () => {
  const bytes = randomBytes(6 * 1024 * 1024 + 1);
  const event = image(bytes);
  event.item.revised_prompt = "Bodrum, Türkiye — Ruyakent’s stone beach";
  event.item.result = `data:image/png;base64,\n${event.item.result}\n`;
  await withProvider([[event, completed]], async requests => {
    assert.deepEqual((await generateArtifactImage(input)).buffer, bytes);
    assert.equal(requests.length, 1);
  });
});

test("malformed large image data fails validation without retrying generation", async () => {
  for (const suffix of ["!", "===", "=AAAA"]) {
    const event = image(Buffer.alloc(4 * 1024 * 1024, 127));
    event.item.result += suffix;
    await withProvider([[event, completed]], async requests => {
      await assert.rejects(generateArtifactImage(input), { code: "image_generation_invalid_result" });
      assert.equal(requests.length, 1);
    });
  }
});

test("a streamed ChatGPT stack overflow retries once and returns the generated bytes", async () => {
  const bytes = Buffer.alloc(4 * 1024 * 1024, 183);
  await withProvider([[failure("Maximum call stack size exceeded")], [image(bytes), completed]], async requests => {
    const result = await generateArtifactImage(input);
    assert.deepEqual(result.buffer, bytes);
    assert.equal(result.providerItemId, "ig_test");
    assert.deepEqual(result.usage, { total_tokens: 23 });
    assert.equal(requests.length, 2);
    assert.deepEqual(requests[1].body, requests[0].body);
  });
});

test("repeated upstream failure remains bounded and preserves its reason for fallback", async () => {
  const turn = [failure("Maximum call stack size exceeded")];
  await withProvider([turn, turn], async requests => {
    await assert.rejects(generateArtifactImage(input), {
      code: "image_generation_upstream_internal_error", message: "Maximum call stack size exceeded",
    });
    assert.equal(requests.length, 2);
  });
});

test("an SDK error event after a partial frame retries instead of publishing the unfinished image", async () => {
  const partial = { type: "response.image_generation_call.partial_image", partial_image_b64: Buffer.from("partial").toString("base64") };
  const error = { type: "error", error: { message: "Maximum call stack size exceeded" } };
  const final = Buffer.from("complete image");
  await withProvider([[partial, error], [image(final), completed]], async requests => {
    assert.deepEqual((await generateArtifactImage(input)).buffer, final);
    assert.equal(requests.length, 2);
  });
});

test("ordinary refusals do not retry or generate another image", async () => {
  await withProvider([[failure("Image generation quota exceeded")]], async requests => {
    await assert.rejects(generateArtifactImage(input), { message: "Image generation quota exceeded" });
    assert.equal(requests.length, 1);
  });
});

test("completed images survive empty final output and are never regenerated", async () => {
  const bytes = Buffer.from("completed image");
  await withProvider([[image(bytes), failure("Maximum call stack size exceeded"), completed]], async requests => {
    assert.deepEqual((await generateArtifactImage(input)).buffer, bytes);
    assert.equal(requests.length, 1);
  });
});

test("invalid image data is not retried as a provider failure", async () => {
  const invalid = image(Buffer.from("image"));
  invalid.item.result = "not base64!";
  await withProvider([[invalid, completed]], async requests => {
    await assert.rejects(generateArtifactImage(input), { code: "image_generation_invalid_result" });
    assert.equal(requests.length, 1);
  });
});

test("cancellation prevents any generation request", async () => {
  await withProvider([], async requests => {
    await assert.rejects(generateArtifactImage({ ...input, signal: AbortSignal.abort() }), { name: "AbortError" });
    assert.equal(requests.length, 0);
  });
});

test("reference images and requested size are preserved on the retry", async () => {
  await withProvider([[failure("Maximum call stack size exceeded")], [image(Buffer.from("edited image"))]], async requests => {
    await generateArtifactImage({ ...input, size: "1536x1024", sourceImages: [{ dataUrl: "data:image/png;base64,AAAA" }] });
    assert.equal(requests[1].body.tools[0].action, "edit");
    assert.equal(requests[1].body.tools[0].size, "1536x1024");
    assert.deepEqual(requests[1].body.input[0].content[1], { type: "input_image", image_url: "data:image/png;base64,AAAA", detail: "auto" });
  });
});
