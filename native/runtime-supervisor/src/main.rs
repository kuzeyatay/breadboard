    fn read_activation<R: BufRead>(reader: &mut R) -> Result<(), SupervisorError> {
        let mut line = Vec::new();
        let count = reader
            .by_ref()
            .take(MAX_ACTIVATION_LINE_BYTES + 1)
            .read_until(b'\n', &mut line)
            .map_err(|error| {
                (
                    "ACTIVATION_READ_FAILED",
                    format!("failed to read supervisor activation: {error}"),
                )
            })?;
        if count == 0 {
            return Err((
                "ACTIVATION_REQUIRED",
                "supervisor stdin reached EOF before activation".into(),
            ));
        }
        if line.len() as u64 > MAX_ACTIVATION_LINE_BYTES {
            return Err((
                "ACTIVATION_TOO_LARGE",
                format!("supervisor activation exceeds {MAX_ACTIVATION_LINE_BYTES} bytes"),
            ));
        }
        if line.last() != Some(&b'\n') {
            return Err((
                "MALFORMED_ACTIVATION",
                "supervisor activation must be newline terminated".into(),
            ));
        }
        while matches!(line.last(), Some(b'\n' | b'\r')) {
            line.pop();
        }
        let activation = serde_json::from_slice::<ActivationMessage>(&line).map_err(|error| {
            (
                "MALFORMED_ACTIVATION",
                format!("supervisor activation is invalid: {error}"),
            )
        })?;
        match activation {
            ActivationMessage::Activate { protocol_version }
                if protocol_version == ACTIVATION_PROTOCOL_VERSION =>
            {
                Ok(())
            }
            ActivationMessage::Activate { protocol_version } => Err((
                "MALFORMED_ACTIVATION",
                format!("unsupported supervisor activation protocol version {protocol_version}"),
            )),
        }
    }

    fn read_control_or_disconnect<R: BufRead>(reader: &mut R) -> ControlCommand {
        let mut line = Vec::new();
        let read = reader
            .by_ref()
            .take(MAX_CONTROL_LINE_BYTES + 1)
            .read_until(b'\n', &mut line);
        let Ok(count) = read else {
            return ControlCommand::ParentDisconnected;
        };
        if count == 0 || line.len() as u64 > MAX_CONTROL_LINE_BYTES {
            return ControlCommand::ParentDisconnected;
        }
        if line.last() != Some(&b'\n') {
            return ControlCommand::ParentDisconnected;
        }
        while matches!(line.last(), Some(b'\n' | b'\r')) {
            line.pop();
        }
        match serde_json::from_slice::<ControlMessage>(&line) {
            Ok(ControlMessage::Stop { force }) => ControlCommand::Stop { force },
            Ok(ControlMessage::InspectLoopbackListener { request_id, port })
                if request_id > 0 && port > 0 =>
            {
                ControlCommand::InspectLoopbackListener { request_id, port }
            }
            Ok(ControlMessage::InspectLoopbackListener { .. }) | Err(_) => {
                ControlCommand::ParentDisconnected
            }
        }
    }

    fn start_control_input() -> Result<ControlInput, SupervisorError> {
        let (activation_tx, activation_rx) = mpsc::sync_channel::<Result<(), SupervisorError>>(1);
        let (command_tx, command_rx) = mpsc::sync_channel::<ControlCommand>(8);
        let control_thread = thread::Builder::new()
            .name("runtime-supervisor-control".into())
            .spawn(move || {
                let stdin = std::io::stdin();
                let mut reader = BufReader::new(stdin.lock());
                let activation = read_activation(&mut reader);
                let activated = activation.is_ok();
                if activation_tx.send(activation).is_err() || !activated {
                    return;
                }

                // Keep the same buffered reader for all control records. A
                // parent may write activation and the first command in one
                // kernel write, and a new reader would discard bytes already
                // buffered here. Inspection requests are bounded and may be
                // repeated; stop and disconnect are terminal for this channel.
                loop {
                    let command = read_control_or_disconnect(&mut reader);
                    let terminal = matches!(
                        command,
                        ControlCommand::Stop { .. } | ControlCommand::ParentDisconnected
                    );
                    if command_tx.send(command).is_err() || terminal {
                        return;
                    }
                }
            })
            .map_err(|error| {
                (
                    "CONTROL_THREAD_FAILED",
                    format!("failed to start control-input thread: {error}"),
                )
            })?;
        Ok(ControlInput {
            activation: activation_rx,
            commands: command_rx,
            _thread: control_thread,
        })
    }

