enum LiveJobLimitAction {
    Keep,
    Apply(u64),
    Terminate,
}

/// Recomputes the total tree ceiling from current system capacity, rather than
/// treating launch-time free commit as a lifetime allocation. Adding the
/// tree's current commit is essential: system free commit already excludes
/// those bytes. Consequently tree growth consumes free commit one-for-one and
/// cannot ratchet this allowance upward.
///
/// Every guarded development tree may tighten its ceiling as external commit
/// pressure rises or restore its manifest ceiling when capacity returns. One
/// process tree at a time may hold the cross-process dynamic-burst lease and
/// grow beyond that manifest ceiling. This keeps the ordinary manifest limit
/// as the leak backstop while allowing a measured operation to borrow live
/// machine headroom without overlapping another tree's borrowed allowance.
fn live_job_limit_action(
    configured_hard_limit_bytes: u64,
    current_effective_hard_limit_bytes: u64,
    current_job_commit_bytes: u64,
    free_system_commit_bytes: u64,
    effective_reserve_bytes: u64,
    guard_band_bytes: u64,
    dynamic_burst_authorized: bool,
) -> LiveJobLimitAction {
    let protected = effective_reserve_bytes.saturating_add(guard_band_bytes);
    if free_system_commit_bytes <= protected {
        if dynamic_burst_authorized {
            return LiveJobLimitAction::Terminate;
        }
        // A non-borrowing tree is not selected as the reserve victim. Remove
        // any stale growth allowance anyway so it cannot worsen the pressure.
        let fence = current_job_commit_bytes.saturating_add(1);
        return if fence < current_effective_hard_limit_bytes {
            LiveJobLimitAction::Apply(fence)
        } else {
            LiveJobLimitAction::Keep
        };
    }
    let safe_growth = free_system_commit_bytes - protected;
    let ceiling = if dynamic_burst_authorized {
        dynamic_commit_burst_ceiling(configured_hard_limit_bytes)
    } else {
        configured_hard_limit_bytes
    };
    let desired = ceiling.min(current_job_commit_bytes.saturating_add(safe_growth));
    // A valid Continue sample always leaves positive growth. Keep the explicit
    // fence for saturated arithmetic and for deterministic fail-closed tests.
    if desired <= current_job_commit_bytes {
        return if dynamic_burst_authorized {
            LiveJobLimitAction::Terminate
        } else {
            LiveJobLimitAction::Keep
        };
    }
    if dynamic_burst_authorized
        && current_effective_hard_limit_bytes > configured_hard_limit_bytes
        && desired <= configured_hard_limit_bytes
    {
        // Do not let hysteresis strand the one global burst lease on a tree
        // that no longer needs borrowed capacity.
        return LiveJobLimitAction::Apply(desired);
    }
    let change = desired.abs_diff(current_effective_hard_limit_bytes);
    if change < SYSTEM_COMMIT_REBALANCE_HYSTERESIS_BYTES {
        LiveJobLimitAction::Keep
    } else {
        LiveJobLimitAction::Apply(desired)
    }
}

fn dynamic_commit_burst_ceiling(configured_hard_limit_bytes: u64) -> u64 {
    configured_hard_limit_bytes
        .saturating_mul(SYSTEM_COMMIT_DYNAMIC_BURST_MULTIPLIER)
        .min(SYSTEM_COMMIT_DYNAMIC_BURST_MAX_BYTES)
        .max(configured_hard_limit_bytes)
}

fn should_request_dynamic_commit_burst(
    configured_hard_limit_bytes: u64,
    current_effective_hard_limit_bytes: u64,
    current_job_commit_bytes: u64,
    free_system_commit_bytes: u64,
    effective_reserve_bytes: u64,
    guard_band_bytes: u64,
) -> bool {
    if configured_hard_limit_bytes == 0
        || current_effective_hard_limit_bytes < configured_hard_limit_bytes
    {
        return false;
    }
    let trigger = configured_hard_limit_bytes
        .saturating_mul(SYSTEM_COMMIT_DYNAMIC_BURST_TRIGGER_PERCENT)
        / 100;
    let protected = effective_reserve_bytes.saturating_add(guard_band_bytes);
    let safe_ceiling =
        current_job_commit_bytes.saturating_add(free_system_commit_bytes.saturating_sub(protected));
    current_job_commit_bytes >= trigger
        && safe_ceiling
            >= configured_hard_limit_bytes.saturating_add(SYSTEM_COMMIT_REBALANCE_HYSTERESIS_BYTES)
        && dynamic_commit_burst_ceiling(configured_hard_limit_bytes) > configured_hard_limit_bytes
}

fn derived_system_commit_reserve_bytes(commit_limit_bytes: u64) -> u64 {
    (commit_limit_bytes / SYSTEM_COMMIT_DERIVED_RESERVE_DIVISOR).clamp(
        SYSTEM_COMMIT_DERIVED_RESERVE_MIN_BYTES,
        SYSTEM_COMMIT_DERIVED_RESERVE_MAX_BYTES,
    )
}

fn supervision_poll_interval_ms(system_commit_guarded: bool) -> u32 {
    if system_commit_guarded {
        SYSTEM_COMMIT_GUARD_POLL_INTERVAL_MS
    } else {
        SUPERVISION_POLL_INTERVAL_MS
    }
}

