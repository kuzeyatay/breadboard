    fn native_u32(bytes: &[u8]) -> Result<u32, ()> {
        let encoded: [u8; size_of::<u32>()] = bytes.try_into().map_err(|_| ())?;
        Ok(u32::from_ne_bytes(encoded))
    }

    /// Parses the native `MIB_TCPTABLE_OWNER_PID` flexible-array encoding
    /// without ever constructing or dereferencing its one-element Rust
    /// binding. The byte bound is independent from the Job PID-list bound:
    /// host-wide listener cardinality is not constrained by this Job.
    fn parse_loopback_listener_owner_pid(table: &[u8], port: u16) -> Result<Option<u32>, ()> {
        if port == 0 || table.len() < size_of::<u32>() || table.len() > MAX_TCP_LISTENER_TABLE_BYTES
        {
            return Err(());
        }
        let count = native_u32(&table[..size_of::<u32>()])? as usize;
        let rows_bytes = count.checked_mul(TCP_OWNER_PID_ROW_BYTES).ok_or(())?;
        let required = size_of::<u32>().checked_add(rows_bytes).ok_or(())?;
        if required > table.len() {
            return Err(());
        }

        let mut owner = None;
        let (rows, remainder) =
            table[size_of::<u32>()..required].as_chunks::<TCP_OWNER_PID_ROW_BYTES>();
        debug_assert!(remainder.is_empty());
        for row in rows {
            let field = |index: usize| {
                let offset = index.checked_mul(size_of::<u32>()).ok_or(())?;
                let end = offset.checked_add(size_of::<u32>()).ok_or(())?;
                native_u32(row.get(offset..end).ok_or(())?)
            };
            let state = field(0)?;
            let local_address = field(1)?;
            let local_port = field(2)?;
            let owner_pid = field(5)?;
            if state != MIB_TCP_STATE_LISTEN as u32
                || local_address.to_ne_bytes() != [127, 0, 0, 1]
                || u16::from_be(local_port as u16) != port
            {
                continue;
            }
            if owner_pid == 0 {
                return Err(());
            }
            match owner {
                Some(existing) if existing != owner_pid => return Err(()),
                Some(_) => {}
                None => owner = Some(owner_pid),
            }
        }
        Ok(owner)
    }

    /// Returns the PID owning the exact IPv4 loopback listening socket. The
    /// outer `Result` distinguishes a trustworthy empty table from an
    /// unavailable/internally inconsistent Windows table query.
    unsafe fn loopback_listener_owner_pid(port: u16) -> Result<Option<u32>, ()> {
        let mut bytes = 0u32;
        let initial = GetExtendedTcpTable(
            null_mut(),
            &mut bytes,
            0,
            2, // AF_INET; avoid enabling the unrelated WinSock surface.
            TCP_TABLE_OWNER_PID_LISTENER,
            0,
        );
        if initial != ERROR_INSUFFICIENT_BUFFER {
            return Err(());
        }

        let allocated_bytes = usize::try_from(bytes).map_err(|_| ())?;
        if allocated_bytes < size_of::<u32>() || allocated_bytes > MAX_TCP_LISTENER_TABLE_BYTES {
            return Err(());
        }
        let mut storage = vec![0u8; allocated_bytes];
        let mut returned_bytes = bytes;
        let queried = GetExtendedTcpTable(
            storage.as_mut_ptr().cast::<c_void>(),
            &mut returned_bytes,
            0,
            2,
            TCP_TABLE_OWNER_PID_LISTENER,
            0,
        );
        if queried != 0 {
            return Err(());
        }
        let returned_bytes = usize::try_from(returned_bytes).map_err(|_| ())?;
        if returned_bytes < size_of::<u32>()
            || returned_bytes > allocated_bytes
            || returned_bytes > MAX_TCP_LISTENER_TABLE_BYTES
        {
            return Err(());
        }
        parse_loopback_listener_owner_pid(&storage[..returned_bytes], port)
    }

    unsafe fn listener_ownership_status(
        job: HANDLE,
        port: u16,
    ) -> (ListenerOwnershipStatus, Option<u32>) {
        let owner_pid = match loopback_listener_owner_pid(port) {
            Ok(owner_pid) => owner_pid,
            Err(()) => return (ListenerOwnershipStatus::Unavailable, None),
        };
        let Some(owner_pid) = owner_pid else {
            return (ListenerOwnershipStatus::Absent, None);
        };
        let Some(job_pids) = job_process_ids(job) else {
            return (ListenerOwnershipStatus::Unavailable, None);
        };
        let status = if job_pids.contains(&(owner_pid as usize)) {
            ListenerOwnershipStatus::Owned
        } else {
            ListenerOwnershipStatus::Unowned
        };
        (status, Some(owner_pid))
    }

