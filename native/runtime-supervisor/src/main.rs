    unsafe fn configure_job_memory_limit(
        job: HANDLE,
        effective_hard_limit_bytes: u64,
    ) -> Result<(), (&'static str, String)> {
        let mut limits: JOBOBJECT_EXTENDED_LIMIT_INFORMATION = zeroed();
        limits.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
        if effective_hard_limit_bytes > 0 {
            limits.BasicLimitInformation.LimitFlags |= JOB_OBJECT_LIMIT_JOB_MEMORY;
            limits.JobMemoryLimit = usize::try_from(effective_hard_limit_bytes)
                .map_err(|_| ("JOB_CONFIG_FAILED", "hard limit does not fit usize".into()))?;
        }
        if SetInformationJobObject(
            job,
            JobObjectExtendedLimitInformation,
            &limits as *const _ as *const c_void,
            size_of::<JOBOBJECT_EXTENDED_LIMIT_INFORMATION>() as u32,
        ) == 0
        {
            return Err((
                "JOB_CONFIG_FAILED",
                format!(
                    "configuring the Job Object memory limit failed with Windows error {}",
                    GetLastError()
                ),
            ));
        }
        Ok(())
    }

