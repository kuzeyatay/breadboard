impl SystemCommitGuardEvidence {
    fn at_launch(
        config: SystemCommitGuardConfig,
        configured_hard_limit_bytes: u64,
        system_commit_bytes: u64,
        system_commit_limit_bytes: u64,
    ) -> Self {
        let launch_free_commit_bytes =
            system_commit_limit_bytes.saturating_sub(system_commit_bytes);
        let launch_derived_reserve_bytes =
            derived_system_commit_reserve_bytes(system_commit_limit_bytes);
        let launch_effective_reserve_bytes = SYSTEM_COMMIT_RESERVE_FLOOR_BYTES
            .max(launch_derived_reserve_bytes)
            .max(config.trusted_reserve_bytes);
        let safe_tree_allowance = launch_free_commit_bytes.saturating_sub(
            launch_effective_reserve_bytes.saturating_add(SYSTEM_COMMIT_RESERVE_GUARD_BAND_BYTES),
        );
        let effective_hard_limit_bytes = configured_hard_limit_bytes.min(safe_tree_allowance);
        Self {
            architecture_reserve_floor_bytes: SYSTEM_COMMIT_RESERVE_FLOOR_BYTES,
            launch_derived_reserve_bytes,
            trusted_reserve_bytes: config.trusted_reserve_bytes,
            launch_effective_reserve_bytes,
            guard_band_bytes: SYSTEM_COMMIT_RESERVE_GUARD_BAND_BYTES,
            expected_commit_bytes: config.expected_commit_bytes,
            configured_hard_limit_bytes,
            effective_hard_limit_bytes,
            launch_system_commit_bytes: system_commit_bytes,
            launch_system_commit_limit_bytes: system_commit_limit_bytes,
            launch_free_commit_bytes,
            pre_resume_system_commit_bytes: None,
            pre_resume_system_commit_limit_bytes: None,
            pre_resume_free_commit_bytes: None,
            pre_resume_effective_hard_limit_bytes: None,
            minimum_observed_free_commit_bytes: launch_free_commit_bytes,
            maximum_observed_derived_reserve_bytes: launch_derived_reserve_bytes,
            maximum_observed_effective_reserve_bytes: launch_effective_reserve_bytes,
            termination_reason: None,
        }
    }

    fn expected_commit_fits(self) -> bool {
        self.effective_hard_limit_bytes > self.expected_commit_bytes
    }

    fn observe_before_resume(
        &mut self,
        system_commit_bytes: u64,
        system_commit_limit_bytes: u64,
    ) -> Result<u64, SystemCommitGuardAction> {
        let free_commit_bytes = system_commit_limit_bytes.saturating_sub(system_commit_bytes);
        self.pre_resume_system_commit_bytes = Some(system_commit_bytes);
        self.pre_resume_system_commit_limit_bytes = Some(system_commit_limit_bytes);
        self.pre_resume_free_commit_bytes = Some(free_commit_bytes);
        if self.observe(system_commit_bytes, system_commit_limit_bytes)
            == SystemCommitGuardAction::Terminate
        {
            return Err(SystemCommitGuardAction::Terminate);
        }
        let tightened_hard_limit = self.effective_hard_limit_bytes.min(
            free_commit_bytes.saturating_sub(
                self.maximum_observed_effective_reserve_bytes
                    .saturating_add(self.guard_band_bytes),
            ),
        );
        if tightened_hard_limit <= self.expected_commit_bytes {
            self.mark_expected_commit_denial();
            return Err(SystemCommitGuardAction::Terminate);
        }
        Ok(tightened_hard_limit)
    }

    /// Records live system pressure for every guarded development tree. Live
    /// victim selection belongs to the cross-process dynamic-burst lease in
    /// the supervision loop; this method only maintains closed telemetry.
    fn observe_live(
        &mut self,
        _environment_profile: EnvironmentProfile,
        system_commit_bytes: u64,
        system_commit_limit_bytes: u64,
    ) -> SystemCommitGuardAction {
        self.record_observation(system_commit_bytes, system_commit_limit_bytes);
        SystemCommitGuardAction::Continue
    }

    fn record_effective_hard_limit(&mut self, effective_hard_limit_bytes: u64) {
        debug_assert!(effective_hard_limit_bytes <= self.effective_hard_limit_bytes);
        self.effective_hard_limit_bytes = effective_hard_limit_bytes;
        self.pre_resume_effective_hard_limit_bytes = Some(effective_hard_limit_bytes);
    }

    fn record_live_effective_hard_limit(&mut self, effective_hard_limit_bytes: u64) {
        debug_assert!(effective_hard_limit_bytes > 0);
        debug_assert!(
            effective_hard_limit_bytes
                <= dynamic_commit_burst_ceiling(self.configured_hard_limit_bytes)
        );
        self.effective_hard_limit_bytes = effective_hard_limit_bytes;
    }

    fn observe(
        &mut self,
        system_commit_bytes: u64,
        system_commit_limit_bytes: u64,
    ) -> SystemCommitGuardAction {
        let free_commit_bytes =
            self.record_observation(system_commit_bytes, system_commit_limit_bytes);
        if free_commit_bytes
            <= self
                .maximum_observed_effective_reserve_bytes
                .saturating_add(self.guard_band_bytes)
        {
            if self.termination_reason.is_none() {
                self.termination_reason =
                    Some(SystemCommitGuardTerminationReason::SystemCommitReserve);
            }
            SystemCommitGuardAction::Terminate
        } else {
            SystemCommitGuardAction::Continue
        }
    }

    fn record_observation(
        &mut self,
        system_commit_bytes: u64,
        system_commit_limit_bytes: u64,
    ) -> u64 {
        let free_commit_bytes = system_commit_limit_bytes.saturating_sub(system_commit_bytes);
        self.minimum_observed_free_commit_bytes = self
            .minimum_observed_free_commit_bytes
            .min(free_commit_bytes);
        let derived_reserve = derived_system_commit_reserve_bytes(system_commit_limit_bytes);
        self.maximum_observed_derived_reserve_bytes = self
            .maximum_observed_derived_reserve_bytes
            .max(derived_reserve);
        self.maximum_observed_effective_reserve_bytes = self
            .maximum_observed_effective_reserve_bytes
            .max(SYSTEM_COMMIT_RESERVE_FLOOR_BYTES)
            .max(derived_reserve)
            .max(self.trusted_reserve_bytes);
        free_commit_bytes
    }

    fn mark_expected_commit_denial(&mut self) {
        self.termination_reason =
            Some(SystemCommitGuardTerminationReason::ExpectedCommitDoesNotFit);
    }

    fn mark_effective_job_limit(&mut self) {
        if self.termination_reason.is_none() {
            self.termination_reason = Some(SystemCommitGuardTerminationReason::EffectiveJobLimit);
        }
    }

    fn mark_system_commit_reserve(&mut self) {
        if self.termination_reason.is_none() {
            self.termination_reason = Some(SystemCommitGuardTerminationReason::SystemCommitReserve);
        }
    }

    fn mark_observation_unavailable(&mut self) {
        if self.termination_reason.is_none() {
            self.termination_reason =
                Some(SystemCommitGuardTerminationReason::SystemCommitObservationUnavailable);
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Options {
    soft_limit_bytes: u64,
    hard_limit_bytes: u64,
    system_commit_guard: Option<SystemCommitGuardConfig>,
    graceful_timeout_ms: u64,
    cwd: String,
    environment_profile: EnvironmentProfile,
    inherited_environment: Vec<String>,
    command: String,
    args: Vec<String>,
}

fn parse_u64(name: &str, value: Option<String>) -> Result<u64, String> {
    value
        .ok_or_else(|| format!("missing value for {name}"))?
        .parse::<u64>()
        .map_err(|_| format!("invalid value for {name}"))
}

fn parse_options<I>(arguments: I) -> Result<Options, String>
where
    I: IntoIterator<Item = String>,
{
    let mut values = arguments.into_iter();
    let mut soft_limit_bytes = 0;
    let mut hard_limit_bytes = 0;
    let mut expected_commit_bytes = None;
    let mut system_commit_reserve_bytes = None;
    let mut graceful_timeout_ms = 5_000;
    let mut cwd = None;
    let mut environment_profile = EnvironmentProfile::Worker;
    let mut environment_profile_seen = false;
    let mut requested_environment = Vec::new();
    let mut target = Vec::new();
    while let Some(value) = values.next() {
        match value.as_str() {
            "--soft-limit-bytes" => soft_limit_bytes = parse_u64(&value, values.next())?,
            "--hard-limit-bytes" => hard_limit_bytes = parse_u64(&value, values.next())?,
            "--expected-commit-bytes" => {
                let parsed = parse_u64(&value, values.next())?;
                if expected_commit_bytes.replace(parsed).is_some() {
                    return Err("--expected-commit-bytes may be specified only once".to_string());
                }
            }
            "--system-commit-reserve-bytes" => {
                let parsed = parse_u64(&value, values.next())?;
                if system_commit_reserve_bytes.replace(parsed).is_some() {
                    return Err(
                        "--system-commit-reserve-bytes may be specified only once".to_string()
                    );
                }
            }
            "--graceful-timeout-ms" => graceful_timeout_ms = parse_u64(&value, values.next())?,
            "--cwd" => {
                let value = values
                    .next()
                    .ok_or_else(|| "missing value for --cwd".to_string())?;
                if cwd.replace(value).is_some() {
                    return Err("--cwd may be specified only once".to_string());
                }
            }
            "--environment-profile" => {
                if environment_profile_seen {
                    return Err("--environment-profile may be specified only once".to_string());
                }
                let value = values
                    .next()
                    .ok_or_else(|| "missing value for --environment-profile".to_string())?;
                environment_profile = EnvironmentProfile::parse(&value)?;
                environment_profile_seen = true;
            }
            "--inherit-env" => {
                let name = values
                    .next()
                    .ok_or_else(|| "missing value for --inherit-env".to_string())?;
                if !is_valid_environment_name(&name) {
                    return Err("invalid inherited environment variable name".to_string());
                }
                requested_environment.push(name);
            }
            "--" => {
                target.extend(values);
                break;
            }
            _ => return Err(format!("unknown option {value}")),
        }
    }
    let command = target
        .first()
        .cloned()
        .ok_or_else(|| "missing target command".to_string())?;
    if command.is_empty() {
        return Err("target command must not be empty".to_string());
    }
    if target.len() > MAX_TARGET_ARGUMENTS + 1 {
        return Err(format!(
            "target has more than {MAX_TARGET_ARGUMENTS} arguments"
        ));
    }
    if target.iter().any(|value| value.contains('\0')) {
        return Err("target command and arguments must not contain NUL".to_string());
    }
    let cwd = cwd.ok_or_else(|| "missing required --cwd".to_string())?;
    if cwd.is_empty() || cwd.contains('\0') {
        return Err("target working directory is invalid".to_string());
    }
    #[cfg(windows)]
    if !std::path::Path::new(&cwd).is_absolute() {
        return Err("target working directory must be absolute".to_string());
    }
    if soft_limit_bytes > 0 && hard_limit_bytes > 0 && soft_limit_bytes >= hard_limit_bytes {
        return Err("soft limit must be lower than hard limit".to_string());
    }
    if hard_limit_bytes > usize::MAX as u64 {
        return Err("hard limit cannot be represented on this platform".to_string());
    }
    let system_commit_guard = match (expected_commit_bytes, system_commit_reserve_bytes) {
        (None, None) => None,
        (Some(expected_commit_bytes), Some(trusted_reserve_bytes)) => {
            if expected_commit_bytes == 0
                || hard_limit_bytes == 0
                || expected_commit_bytes >= hard_limit_bytes
                || trusted_reserve_bytes < SYSTEM_COMMIT_RESERVE_FLOOR_BYTES
            {
                return Err("system commit guard values are invalid".to_string());
            }
            Some(SystemCommitGuardConfig {
                expected_commit_bytes,
                trusted_reserve_bytes,
            })
        }
        _ => return Err(
            "--expected-commit-bytes and --system-commit-reserve-bytes must be supplied together"
                .to_string(),
        ),
    };
    let mut inherited_environment = Vec::with_capacity(requested_environment.len());
    for name in requested_environment {
        let canonical_name = environment_profile
            .canonical_environment_name(&name)
            .ok_or_else(|| {
                "inherited environment variable is outside the selected profile".to_string()
            })?;
        if inherited_environment
            .iter()
            .any(|existing: &String| existing.eq_ignore_ascii_case(canonical_name))
        {
            return Err("duplicate inherited environment variable name".to_string());
        }
        inherited_environment.push(canonical_name.to_string());
    }
    Ok(Options {
        soft_limit_bytes,
        hard_limit_bytes,
        system_commit_guard,
        graceful_timeout_ms: graceful_timeout_ms.clamp(100, 300_000),
        cwd,
        environment_profile,
        inherited_environment,
        command,
        args: target.into_iter().skip(1).collect(),
    })
}

fn is_valid_environment_name(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= MAX_ENVIRONMENT_NAME_BYTES
        && value
            .bytes()
            .all(|byte| byte.is_ascii_graphic() && byte != b'=')
}

#[derive(Serialize)]
struct ErrorEvent<'a> {
    #[serde(rename = "type")]
    kind: &'static str,
    code: &'a str,
    message: &'a str,
}

fn write_json_line(value: &impl Serialize) -> Result<(), String> {
    let stdout = std::io::stdout();
    let mut stdout = stdout.lock();
    serde_json::to_writer(&mut stdout, value)
        .map_err(|error| format!("serializing protocol event failed: {error}"))?;
    stdout
        .write_all(b"\n")
        .and_then(|_| stdout.flush())
        .map_err(|error| format!("writing protocol event failed: {error}"))
}

fn main() {
    let options = match parse_options(env::args().skip(1)) {
        Ok(options) => options,
        Err(message) => {
            let _ = write_json_line(&ErrorEvent {
                kind: "error",
                code: "MALFORMED_PROTOCOL",
                message: &message,
            });
            std::process::exit(64);
        }
    };

    #[cfg(windows)]
    match windows_runtime::run(options) {
        Ok(code) => {
            // Rust forwards this value to ExitProcess on Windows. Preserve the
            // target's complete exit status instead of reporting success after
            // a failed child.
            std::process::exit(code as i32);
        }
        Err((code, message)) => {
            let _ = write_json_line(&ErrorEvent {
                kind: "error",
                code,
                message: &message,
            });
            std::process::exit(1);
        }
    }

    #[cfg(not(windows))]
    {
        let _ = options;
        let _ = write_json_line(&ErrorEvent {
            kind: "error",
            code: "UNSUPPORTED_PLATFORM",
            message: "runtime-supervisor is a Windows-only containment helper",
        });
        std::process::exit(69);
    }
}

