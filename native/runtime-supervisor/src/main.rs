    /// A session-wide mutex serializes development-only commit bursts across
    /// every Runtime V2 process supervisor. Failure to open or acquire it is a
    /// safe static-limit fallback, never permission to borrow untracked slack.
    struct DynamicCommitBurstLease {
        handle: Option<Handle>,
        held: bool,
    }

    impl DynamicCommitBurstLease {
        fn open() -> Self {
            Self::open_named("Local\\Breadboard.RuntimeV2.DynamicCommitBurst.v1")
        }

        fn open_named(name: &str) -> Self {
            let name = wide(OsStr::new(name));
            let raw = unsafe { CreateMutexW(null(), 0, name.as_ptr()) };
            Self {
                handle: (!raw.is_null()).then_some(Handle(raw)),
                held: false,
            }
        }

        fn held(&self) -> bool {
            self.held
        }

        fn try_acquire(&mut self) -> bool {
            if self.held {
                return true;
            }
            let Some(handle) = self.handle.as_ref() else {
                return false;
            };
            self.held = matches!(
                unsafe { WaitForSingleObject(handle.0, 0) },
                WAIT_OBJECT_0 | WAIT_ABANDONED
            );
            self.held
        }

        fn release(&mut self) {
            if !self.held {
                return;
            }
            if let Some(handle) = self.handle.as_ref() {
                unsafe {
                    let _ = ReleaseMutex(handle.0);
                }
            }
            self.held = false;
        }
    }

    impl Drop for DynamicCommitBurstLease {
        fn drop(&mut self) {
            self.release();
        }
    }

    struct AttributeList {
        storage: Vec<usize>,
        pointer: *mut c_void,
    }

    impl AttributeList {
        unsafe fn for_handles_and_job(
            handles: &mut [HANDLE],
            jobs: &mut [HANDLE],
        ) -> Result<Self, (&'static str, String)> {
            let mut bytes = 0usize;
            let _ = InitializeProcThreadAttributeList(null_mut(), 2, 0, &mut bytes);
            if bytes == 0 {
                return Err((
                    "SPAWN_FAILED",
                    "InitializeProcThreadAttributeList did not report a buffer size".into(),
                ));
            }
            let words = bytes
                .checked_add(size_of::<usize>() - 1)
                .ok_or(("SPAWN_FAILED", "attribute-list size overflow".into()))?
                / size_of::<usize>();
            let mut storage = vec![0usize; words];
            let pointer = storage.as_mut_ptr().cast::<c_void>();
            if InitializeProcThreadAttributeList(pointer, 2, 0, &mut bytes) == 0 {
                return Err((
                    "SPAWN_FAILED",
                    "InitializeProcThreadAttributeList failed".into(),
                ));
            }
            if UpdateProcThreadAttribute(
                pointer,
                0,
                PROC_THREAD_ATTRIBUTE_HANDLE_LIST as usize,
                handles.as_mut_ptr().cast::<c_void>(),
                std::mem::size_of_val(handles),
                null_mut(),
                null(),
            ) == 0
            {
                DeleteProcThreadAttributeList(pointer);
                return Err((
                    "SPAWN_FAILED",
                    "UpdateProcThreadAttribute(handle list) failed".into(),
                ));
            }
            if UpdateProcThreadAttribute(
                pointer,
                0,
                PROC_THREAD_ATTRIBUTE_JOB_LIST as usize,
                jobs.as_mut_ptr().cast::<c_void>(),
                std::mem::size_of_val(jobs),
                null_mut(),
                null(),
            ) == 0
            {
                DeleteProcThreadAttributeList(pointer);
                return Err((
                    "JOB_ASSIGN_FAILED",
                    "UpdateProcThreadAttribute(job list) failed".into(),
                ));
            }
            Ok(Self { storage, pointer })
        }
    }

    impl Drop for AttributeList {
        fn drop(&mut self) {
            // Keep the backing allocation alive until the OS-owned attribute
            // list has been deleted.
            let _ = self.storage.len();
            unsafe { DeleteProcThreadAttributeList(self.pointer) };
        }
    }

    fn wide(value: &OsStr) -> Vec<u16> {
        value.encode_wide().chain(Some(0)).collect()
    }

    /// Creates a new environment block instead of inheriting the supervisor's
    /// complete ambient block. The trusted caller passes names only; values
    /// remain in the supervisor environment and never enter argv or protocol
    /// output.
    fn child_environment_block(
        profile: EnvironmentProfile,
        allowlist: &[String],
    ) -> Result<Vec<u16>, SupervisorError> {
        child_environment_block_with_lookup(profile, allowlist, |name| std::env::var_os(name))
    }

    fn child_environment_block_with_lookup<F>(
        profile: EnvironmentProfile,
        allowlist: &[String],
        mut lookup: F,
    ) -> Result<Vec<u16>, SupervisorError>
    where
        F: FnMut(&str) -> Option<OsString>,
    {
        let mut names = REQUIRED_CHILD_ENVIRONMENT
            .iter()
            .map(|name| (*name).to_string())
            .collect::<Vec<_>>();
        for name in allowlist {
            let canonical_name = profile.canonical_environment_name(name).ok_or((
                "SPAWN_FAILED",
                "the requested child environment does not match its selected profile".to_string(),
            ))?;
            if !names
                .iter()
                .any(|existing| existing.eq_ignore_ascii_case(canonical_name))
            {
                names.push(canonical_name.to_string());
            }
        }

        let mut variables = Vec::<(String, OsString)>::with_capacity(names.len());
        for name in names {
            let value = lookup(&name).ok_or((
                "SPAWN_FAILED",
                "an allowlisted child environment variable was unavailable".to_string(),
            ))?;
            variables.push((name, value));
        }
        variables.sort_by(|left, right| {
            left.0
                .to_ascii_lowercase()
                .cmp(&right.0.to_ascii_lowercase())
        });

        let mut block = Vec::<u16>::new();
        for (name, value) in variables {
            let mut entry = OsStr::new(&name).encode_wide().collect::<Vec<_>>();
            entry.push('=' as u16);
            entry.extend(value.as_os_str().encode_wide());
            if entry.contains(&0) {
                return Err((
                    "SPAWN_FAILED",
                    "an allowlisted child environment variable was invalid".to_string(),
                ));
            }
            entry.push(0);
            let final_size = block
                .len()
                .checked_add(entry.len())
                .and_then(|length| length.checked_add(1))
                .ok_or((
                    "SPAWN_FAILED",
                    "the allowlisted child environment is too large".to_string(),
                ))?;
            if final_size > MAX_WINDOWS_ENVIRONMENT_UTF16 {
                return Err((
                    "SPAWN_FAILED",
                    "the allowlisted child environment is too large".to_string(),
                ));
            }
            block.extend(entry);
        }
        // Every entry already ends in NUL; this is the second NUL that
        // terminates the complete environment block.
        block.push(0);
        Ok(block)
    }

    fn quote(value: &str) -> String {
        if !value.is_empty() && !value.chars().any(|c| c.is_whitespace() || c == '"') {
            return value.to_string();
        }
        let mut result = String::from("\"");
        let mut slashes = 0;
        for ch in value.chars() {
            if ch == '\\' {
                slashes += 1;
            } else if ch == '"' {
                result.push_str(&"\\".repeat(slashes * 2 + 1));
                result.push('"');
                slashes = 0;
            } else {
                result.push_str(&"\\".repeat(slashes));
                slashes = 0;
                result.push(ch);
            }
        }
        result.push_str(&"\\".repeat(slashes * 2));
        result.push('"');
        result
    }

