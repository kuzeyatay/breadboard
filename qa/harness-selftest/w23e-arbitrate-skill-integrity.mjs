#!/usr/bin/env node

/**
 * W2-3E / SKILL_INTEGRITY_PIN — settle five behavioural targets by executing
 * the integrity gate rather than reading it.
 *
 * The claim under test is not "the skill directory exists". It is that a
 * reviewed, unmodified skill verifies against its pinned hash on any checkout
 * of the reviewed commit and stays usable, while a modified one is refused at
 * every boundary that would ship its guidance. Those are two different
 * failures with opposite severities, so both directions are executed here.
 *
 * The decisive question is portability: a pin is a promise about content, but
 * it is computed over bytes, and git rewrites bytes at checkout. So the file is
 * rendered under both of the repository's possible checkout policies and each
 * rendering is hashed against the pin.
 *
 * Run from `dashboard/` with --experimental-strip-types.
 */

import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { pathToFileURL } from "node:url";

const outPath = path.resolve(process.argv[2] ?? "skill-integrity-arbitration.json");
const dashboardRoot = process.cwd();
const repoRoot = path.resolve(dashboardRoot, "..");
const load = (relative) => import(pathToFileURL(path.join(dashboardRoot, relative)).href);

const { listApprovedSkills, listInstalledLocalSkills } = await load("src/lib/hermes/skills.ts");
const { skillAvailableForContext, resolveCommandMessage } = await load("src/lib/hermes/commands.ts");

const sha256 = (buffer) => crypto.createHash("sha256").update(buffer).digest("hex");
const asLf = (text) => text.replace(/\r\n/g, "\n");
const asCrlf = (text) => asLf(text).replace(/\n/g, "\r\n");

const registry = JSON.parse(
  fs.readFileSync(path.join(repoRoot, ".agents/skills/registry.json"), "utf8"),
);

const SKILLS = ["bullshit-detector", "premortem"];

// --- 1. what the checkout can actually produce ---------------------------
//
// `git cat-file blob` is the committed content with no checkout filter applied.
// A checkout writes that blob verbatim under core.autocrlf=false, and CRLF
// under core.autocrlf=true. So those two renderings are the complete set of
// byte sequences any checkout of this commit can put on disk.
function committedBlob(relative) {
  const result = spawnSync("git", ["cat-file", "blob", `HEAD:${relative}`], {
    cwd: repoRoot,
    encoding: "buffer",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0) return null;
  return result.stdout;
}

const portability = [];
for (const slug of SKILLS) {
  const relative = `.agents/skills/${slug}/SKILL.md`;
  const absolute = path.join(repoRoot, relative);
  const onDisk = fs.readFileSync(absolute);
  const blob = committedBlob(relative);
  const entry = registry.skills?.[slug] ?? {};
  const pin = typeof entry.localHash === "string" ? entry.localHash : null;

  const blobText = blob ? blob.toString("utf8") : null;
  const renderings = blobText === null
    ? {}
    : {
        "checkout core.autocrlf=false (blob verbatim)": sha256(Buffer.from(asLf(blobText), "utf8")),
        "checkout core.autocrlf=true (CRLF)": sha256(Buffer.from(asCrlf(blobText), "utf8")),
      };

  portability.push({
    slug,
    pin,
    onDiskSha256: sha256(onDisk),
    onDiskHasCrlf: onDisk.includes(0x0d),
    onDiskMatchesPin: sha256(onDisk) === pin,
    committedBlobPresent: blob !== null,
    reachableRenderings: renderings,
    pinReachableByAnyCheckout: Object.values(renderings).includes(pin),
    whichCheckoutReproducesPin:
      Object.entries(renderings).find(([, hash]) => hash === pin)?.[0] ?? null,
    contentIdenticalAcrossRenderings: true,
    fileHashesEntryMatchesLocalHash: entry.fileHashes?.["SKILL.md"] === pin,
    reviewState: entry.reviewState ?? null,
  });
}

// --- 2. where the pin actually came from ---------------------------------
//
// One of the two skills is generated by a checked-in build script. If the pin
// equals the hash of that script's raw in-memory output, the pin was taken
// before git ever touched the bytes, which is the whole defect.
let generatorEvidence = null;
try {
  const { buildSkill } = await import(
    pathToFileURL(path.join(repoRoot, "scripts/build-bullshit-detector-skill.mjs")).href
  );
  const clone = fs.readFileSync(
    path.join(repoRoot, "bullshit-detector/skills/analysis/bullshit-detector/SKILL.md"),
    "utf8",
  );
  const built = buildSkill(clone);
  const shipped = fs.readFileSync(
    path.join(repoRoot, ".agents/skills/bullshit-detector/SKILL.md"),
    "utf8",
  );
  const pin = registry.skills["bullshit-detector"].localHash;
  generatorEvidence = {
    generator: "scripts/build-bullshit-detector-skill.mjs :: buildSkill",
    contentIdenticalToShipped: asLf(built) === asLf(shipped),
    rawOutputHasMixedLineEndings: built.includes("\r\n") && /(?<!\r)\n/.test(built),
    shaOfRawGeneratorOutput: sha256(Buffer.from(built, "utf8")),
    pinEqualsRawGeneratorOutput: sha256(Buffer.from(built, "utf8")) === pin,
    shaOfShippedOnDisk: sha256(Buffer.from(shipped, "utf8")),
  };
} catch (error) {
  generatorEvidence = { error: error instanceof Error ? error.message : String(error) };
}

// --- 3. the runtime consequence, executed --------------------------------
const runtime = [];
for (const slug of SKILLS) {
  for (const surface of ["dashboard_terminal", "garden_chat"]) {
    const skill = listApprovedSkills(surface).find((candidate) => candidate.slug === slug);
    runtime.push({
      slug,
      surface,
      listed: Boolean(skill),
      availability: skill?.availability ?? null,
      enabled: skill?.enabled ?? null,
      healthy: skill?.healthy ?? null,
      installedInCatalog: listInstalledLocalSkills(surface).some((c) => c.slug === slug),
      availableForDispatch: skill
        ? skillAvailableForContext(skill, { surface, mode: "knowledge" })
        : false,
    });
  }
  runtime.push({
    slug,
    surface: "quartz_ai",
    listed: listApprovedSkills("quartz_ai").some((c) => c.slug === slug),
    note: "the anonymous public surface must never be offered these",
  });
}

// The end-to-end consequence: does an explicit ask actually dispatch?
let commandResolution = null;
try {
  const resolved = await resolveCommandMessage(1, "/premortem Run a premortem for our September launch", process.cwd(), {
    mode: "knowledge",
    surface: "dashboard_terminal",
  });
  commandResolution = {
    dispatched: true,
    invocations: resolved.invocations.map((invocation) => invocation.slug),
    guidanceAttached: /Reviewed skill guidance: premortem/.test(resolved.text),
  };
} catch (error) {
  commandResolution = {
    dispatched: false,
    error: error instanceof Error ? error.message : String(error),
  };
}

// --- 4. the security direction: is a REAL modification still refused? ----
//
// The gate must keep its teeth. Every boundary that ships guidance is checked
// against a stand-in skill whose integrity failed, and against one that passed.
const gateDirections = [];
const template = listApprovedSkills("dashboard_terminal")[0] ?? {
  slug: "stand-in",
  classification: "eligible_general",
  compatibleSurfaces: ["assistant", "garden"],
  availability: "ready",
};
for (const [label, overrides] of [
  ["integrity failed", { enabled: false, healthy: false }],
  ["integrity passed", { enabled: true, healthy: true }],
  ["enabled but unhealthy", { enabled: true, healthy: false }],
  ["healthy but disabled", { enabled: false, healthy: true }],
]) {
  const candidate = {
    ...template,
    classification: "eligible_general",
    availability: "ready",
    compatibleSurfaces: ["assistant", "garden", "quartz"],
    ...overrides,
  };
  gateDirections.push({
    case: label,
    ...overrides,
    dispatchAllowed: skillAvailableForContext(candidate, {
      surface: "dashboard_terminal",
      mode: "knowledge",
    }),
  });
}

// Which consumers actually apply the gate, read from their own source.
const consumerSource = (relative) => fs.readFileSync(path.join(dashboardRoot, relative), "utf8");
const consumerGates = {
  "super-agent.ts :: skillEntries (what the model is told it can use)":
    /listApprovedSkills\([\s\S]{0,120}?\.filter\(\s*\(skill\)\s*=>\s*[\s\S]{0,80}?skill\.enabled\s*&&\s*[\s\S]{0,20}?skill\.healthy/.test(
      consumerSource("src/lib/hermes/super-agent.ts"),
    ),
  "commands.ts :: skillAvailableForContext (whether a slash command dispatches)":
    /if\s*\(!skill\.enabled\s*\|\|\s*!skill\.healthy\)\s*return false/.test(
      consumerSource("src/lib/hermes/commands.ts"),
    ),
  "api/hermes/tools/skill/route.ts :: skill_open (whether guidance is served)":
    /candidate\.enabled\s*&&\s*[\s\S]{0,20}?candidate\.healthy/.test(
      consumerSource("src/app/api/hermes/tools/skill/route.ts"),
    ),
};

// --- invariants ----------------------------------------------------------
const invariants = [];
const record = (name, holds, detail) => invariants.push({ name, holds, detail });

record(
  "an unmodified reviewed skill verifies on at least one real checkout of the reviewed commit",
  portability.every((entry) => entry.pinReachableByAnyCheckout),
  portability
    .map((entry) => `${entry.slug}: ${entry.whichCheckoutReproducesPin ?? "NO checkout reproduces the pin"}`)
    .join("; "),
);
record(
  "an unmodified reviewed skill verifies on THIS repository's own checkout policy",
  portability.every((entry) => entry.onDiskMatchesPin),
  portability.map((entry) => `${entry.slug}: onDiskMatchesPin=${entry.onDiskMatchesPin}`).join("; "),
);
record(
  "a verified skill is usable on both authenticated chat surfaces",
  runtime
    .filter((entry) => entry.surface !== "quartz_ai")
    .every((entry) => entry.availableForDispatch === true),
  runtime
    .filter((entry) => entry.surface !== "quartz_ai")
    .map((entry) => `${entry.slug}/${entry.surface}: dispatch=${entry.availableForDispatch}`)
    .join("; "),
);
record(
  "an explicit ask reaches the skill and carries its reviewed guidance",
  commandResolution.dispatched === true && commandResolution.guidanceAttached === true,
  commandResolution.dispatched
    ? `invocations=${JSON.stringify(commandResolution.invocations)}`
    : `refused: ${commandResolution.error}`,
);
record(
  "the anonymous public surface is never offered these skills",
  runtime.filter((entry) => entry.surface === "quartz_ai").every((entry) => entry.listed === false),
  "a tool that fetches arbitrary URLs must not reach an unauthenticated surface",
);
record(
  "a skill whose integrity failed cannot dispatch",
  gateDirections.find((entry) => entry.case === "integrity failed")?.dispatchAllowed === false &&
    gateDirections.find((entry) => entry.case === "enabled but unhealthy")?.dispatchAllowed === false &&
    gateDirections.find((entry) => entry.case === "healthy but disabled")?.dispatchAllowed === false,
  "the control must keep its teeth in every partial-failure combination",
);
record(
  "a skill whose integrity passed can dispatch",
  gateDirections.find((entry) => entry.case === "integrity passed")?.dispatchAllowed === true,
  "otherwise the gate refuses everything, which satisfies 'it refuses' without being the contract",
);
record(
  "every boundary that would ship guidance applies the integrity gate",
  Object.values(consumerGates).every(Boolean),
  JSON.stringify(consumerGates),
);

const allHold = invariants.every((entry) => entry.holds);
const brokenInvariants = invariants.filter((entry) => !entry.holds).map((entry) => entry.name);

const summary = {
  generatedAt: new Date().toISOString(),
  subRoot: "SKILL_INTEGRITY_PIN",
  boundary: {
    verifier: "dashboard/src/lib/hermes/skills.ts :: listApprovedSkillsAtRoot (integrityVerified -> enabled/healthy)",
    gate: "dashboard/src/lib/hermes/commands.ts :: skillAvailableForContext",
    method:
      "The committed blob was rendered under both checkout policies the repository can apply and each rendering hashed against the registry pin; the runtime consequence was then read from the real skill list and the real command resolver.",
  },
  portability,
  generatorEvidence,
  runtime,
  commandResolution,
  gateDirections,
  consumerGates,
  invariants,
  allInvariantsHold: allHold,
  brokenInvariants,
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${JSON.stringify(summary, null, 2)}\n`, "utf8");

for (const entry of portability) {
  console.log(
    `[skill-integrity] ${entry.slug}: pin reachable by a checkout = ${entry.pinReachableByAnyCheckout} (${entry.whichCheckoutReproducesPin ?? "none"}), on-disk matches = ${entry.onDiskMatchesPin}`,
  );
}
for (const entry of invariants) {
  console.log(`  ${entry.holds ? "HOLDS " : "BROKEN"} ${entry.name}`);
}
