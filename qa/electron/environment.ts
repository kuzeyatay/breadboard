/**
 * Every QA launch gets one directory below this root. Nothing in this module
 * ever removes the root itself; cleanup is limited to a marker-verified child.
 */
export const QA_RUNTIME_DIRECTORY = "breadboard-qa-runtime";
export const QA_RUN_MARKER = ".breadboard-qa-run.json";

export type QaPreservePolicy = "never" | "on-failure" | "always";
export type QaRunOutcome = "passed" | "failed" | "interrupted";
export type QaServiceProfile = "critical";
export type QaDesktopConfigProfile = "isolated-disabled" | "production-required";

export interface QaRunPaths {
  readonly repoRoot: string;
  readonly runtimeRoot: string;
  readonly runRoot: string;
  readonly userDataDir: string;
  /** The desktop resolver's mutable root: `<userDataDir>/Data`. */
  readonly dataDir: string;
  readonly homeDir: string;
  readonly appDataDir: string;
  readonly localAppDataDir: string;
  readonly tempDir: string;
  readonly downloadsDir: string;
  readonly artifactsDir: string;
  readonly diagnosticsDir: string;
  readonly serviceLogsDir: string;
  /** Shared ChatMock writer/dashboard reader ledger inside disposable data. */
  readonly councilLedgerDir: string;
  /** Empty managed-policy root preventing Hermes machine-global fallback. */
  readonly hermesManagedDir: string;
  readonly hermesFilesDir: string;
  readonly comfyUiRuntimeDir: string;
  readonly comfyUiEnvDir: string;
  readonly optionalSourcesDir: string;
  readonly optionalStateDir: string;
  readonly markerFile: string;
}

export interface QaBootstrapValues {
  /** QA-only invite created in the isolated desktop config. */
  readonly initialInviteCode: string;
  /** In-memory credentials for a user that scenarios may register. */
  readonly auth: {
    readonly inviteCode: string;
    readonly username: string;
    readonly email: string;
    readonly password: string;
  };
}

export interface CreateQaEnvironmentOptions {
  /** Defaults to two directories above this file. */
  repoRoot?: string;
  /** Defaults to `<os temp>/breadboard-qa-runtime`. */
  runtimeRoot?: string;
  /** A filesystem-safe id. A timestamp/pid/random id is generated by default. */
  runId?: string;
  preserve?: QaPreservePolicy;
  /** Isolated critical local services. Broader profiles are intentionally rejected. */
  serviceProfile?: QaServiceProfile;
  /** Source of the small OS allowlist. Defaults to `process.env`. */
  baseEnv?: NodeJS.ProcessEnv;
  /** Additional inherited keys. Secret-looking names require explicit opt-in. */
  passthroughEnv?: readonly string[];
  /** Explicit launch-environment overrides. `undefined` removes a key. */
  env?: NodeJS.ProcessEnv;
  /**
   * Secret-looking override names that are known to contain disposable QA
   * values. Real user credentials must never be added here.
   */
  allowCredentialEnv?: readonly string[];
  /** Seed a QA-only desktop config; integrations stay disabled unless explicitly required. */
  seedDesktopConfig?: boolean;
  /** Defaults to disabled; completion burn-in may require the real GBrain service. */
  gbrainMode?: "disabled" | "required";
  /** Full desktop integration policy. Defaults to isolated-disabled. */
  desktopConfigProfile?: QaDesktopConfigProfile;
  /**
   * Optional read-only reference to the normal ChatMock provider session.
   * This is a path, never credential contents, and is not copied into QA.
   */
  providerAuthFile?: string;
}

export interface QaCleanupResult {
  readonly path: string;
  readonly removed: boolean;
  readonly preserved: boolean;
  readonly reason: string;
}

export interface QaRunEnvironment {
  readonly runId: string;
  readonly paths: QaRunPaths;
  readonly env: NodeJS.ProcessEnv;
  /** Append these to the Electron entrypoint arguments. */
  readonly launchArgs: readonly string[];
  /** Alias useful when composing `electron.launch({ args: [...] })`. */
  readonly electronArgs: readonly string[];
  readonly preserve: QaPreservePolicy;
  readonly bootstrap: QaBootstrapValues;
  cleanup(outcome?: QaRunOutcome): Promise<QaCleanupResult>;
}

